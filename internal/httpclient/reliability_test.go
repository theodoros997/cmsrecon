func TestRetriesTransientAnswers(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch calls.Add(1) {
		case 1:
			w.Header().Set("Retry-After", "0")
			w.WriteHeader(http.StatusTooManyRequests)
		case 2:
			w.WriteHeader(http.StatusBadGateway)
		default:
			w.Write([]byte("ok"))
		}
	}))
	defer srv.Close()
	c := newClient(t, options(t, srv.URL))
	res, err := c.Get(context.Background(), srv.URL+"/")
	if err != nil || res.StatusCode != 200 || string(res.Body) != "ok" {
		t.Fatalf("got %v %+v", err, res)
	}
	if st := c.Stats(); st.Retries != 2 || st.Requests != 3 {
		t.Errorf("stats = %+v, want 2 retries in 3 requests", st)
	}

	// A POST is never sent twice.
	calls.Store(0)
	res, _ = c.Do(context.Background(), Request{Method: http.MethodPost, URL: srv.URL + "/", Body: []byte("x")})
	if res == nil || res.StatusCode != http.StatusTooManyRequests || calls.Load() != 1 {
		t.Errorf("POST: %+v after %d calls", res, calls.Load())
	}
}

func TestRetryAfterIsHonoured(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if calls.Add(1) == 1 {
			w.Header().Set("Retry-After", "1")
			w.WriteHeader(http.StatusServiceUnavailable)
			return
		}
		w.Write([]byte("ok"))
	}))
	defer srv.Close()
	c := newClient(t, options(t, srv.URL))
	start := time.Now()
	if res, err := c.Get(context.Background(), srv.URL+"/"); err != nil || res.StatusCode != 200 {
		t.Fatalf("got %v %+v", err, res)
	}
	if d := time.Since(start); d < 900*time.Millisecond {
		t.Errorf("retried after %s, before the 1s Retry-After", d)
	}
}

func TestBlockPages(t *testing.T) {
	for _, tt := range []struct {
		name   string
		status int
		header string
		body   string
		want   string
		site   bool
	}{
		{"rate limit", 429, "", "slow down", "rate limit", true},
		{"cloudflare header", 403, "challenge", "<html>", "Cloudflare challenge", true},
		{"cloudflare page", 503, "", "<title>Just a moment...</title><script src=/cdn-cgi/challenge-platform/cf-chl-x>", "Cloudflare challenge", true},
		{"wordfence lockout", 503, "", "<h1>Your access to this site has been limited by the site owner</h1>", "Wordfence lockout", true},
		{"wordfence rule", 403, "", "<p>Generated by Wordfence at Tue, 3 Nov 2026</p>", "Wordfence block", false},
		{"sucuri", 403, "", "<title>Access Denied - Sucuri Website Firewall</title>", "Sucuri firewall block", true},
		{"overload", 502, "", "Bad Gateway", "server overload", true},
		{"plain 403", 403, "", "<title>403 Forbidden</title>", "", false},
		{"plain 404", 404, "", "Not found", "", false},
		{"plain 500", 500, "", "Fatal error", "", false},
	} {
		h := http.Header{}
		if tt.header != "" {
			h.Set("Cf-Mitigated", tt.header)
		}
		got, site := blockedBy(tt.status, h, []byte(tt.body))
		if got != tt.want || site != tt.site {
			t.Errorf("%s: blockedBy = %q, %v; want %q, %v", tt.name, got, site, tt.want, tt.site)
		}
	}
}

func TestCircuitBreaker(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/ok" {
			w.Write([]byte("ok"))
			return
		}
		w.Header().Set("Retry-After", "0")
		w.WriteHeader(http.StatusTooManyRequests)
	}))
	defer srv.Close()
	c := newClient(t, options(t, srv.URL))
	var tripped atomic.Int32
	var reason atomic.Value
	c.OnFailing(func(r string) { tripped.Add(1); reason.Store(r) })
	ctx := context.Background()
	// Successes in between keep it closed.
	for range tripAfter + 5 {
		c.Get(ctx, srv.URL+"/limited")
		c.Get(ctx, srv.URL+"/ok")
	}
	if tripped.Load() != 0 || c.Failing() != "" {
		t.Fatalf("tripped while the site still answered: %q", c.Failing())
	}
	for range tripAfter + 5 {
		c.Get(ctx, srv.URL+"/limited")
	}
	if tripped.Load() != 1 || !strings.Contains(c.Failing(), "rate limit (HTTP 429)") {
		t.Errorf("tripped %d times: %q", tripped.Load(), c.Failing())
	}
	if r, _ := reason.Load().(string); !strings.Contains(r, "in a row") {
		t.Errorf("reason = %q", r)
	}
}

func TestCookiesAndEncoding(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if _, err := r.Cookie("lb"); err != nil {
			http.SetCookie(w, &http.Cookie{Name: "lb", Value: "node-2", Path: "/"})
			http.Redirect(w, r, "/", http.StatusFound)
			return
		}
		w.Write([]byte(strings.Repeat("compressible ", 200)))
	}))
	defer srv.Close()
	o := options(t, srv.URL)
	o.Headers.Set("Accept-Encoding", "gzip, deflate, br")
	c := newClient(t, o)
	ctx := context.Background()
	first, err := c.Get(ctx, srv.URL+"/")
	if err != nil || !first.IsRedirect() {
		t.Fatalf("first = %v %+v", err, first)
	}
	second, err := c.Get(ctx, srv.URL+"/")
	if err != nil || second.StatusCode != 200 {
		t.Fatalf("the cookie the site set was not sent back: %v %+v", err, second)
	}
	if !strings.HasPrefix(string(second.Body), "compressible") {
		t.Errorf("a user Accept-Encoding left the body compressed: %q", second.Body[:min(20, len(second.Body))])
	}
}
